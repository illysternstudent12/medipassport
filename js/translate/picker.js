// Searchable global language selector + live AI settings.
import { icon } from '../icons.js';
import { LANGS, langInfo } from './glossary.js';
import { aiOn, aiSettings, saveAiSettings, clearAiCache } from './ai.js';
import { openSheet, closeSheet, toast } from '../app/ui.js';

const esc = (v) => String(v ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

function row(l, current, live) {
  const locked = !l.sim && !live;
  return `<li><button type="button" class="lrow ${l.code === current ? 'is-current' : ''} ${locked ? 'is-locked' : ''}" data-lang="${l.code}" data-locked="${locked}"
      data-q="${esc(`${l.name} ${l.native} ${l.code}`.toLowerCase())}" lang="${l.code}">
    <span class="lrow__native" dir="${l.rtl ? 'rtl' : 'ltr'}">${esc(l.native)}</span>
    <span class="lrow__en" lang="en">${esc(l.name)}${l.rtl ? ' · RTL' : ''}</span>
    <span class="lrow__tag" lang="en">${l.sim ? 'Offline' : locked ? `${icon('lock')} Live AI` : `${icon('sparkle')} Live AI`}</span>
    ${l.code === current ? `<span class="lrow__check">${icon('check')}</span>` : ''}
  </button></li>`;
}

/**
 * Open the language selector.
 * @param {{ current: string, suggested?: string[], title?: string, onPick: (code: string) => void }} o
 */
export function openLanguagePicker({ current, suggested = [], title = 'Translate to', onPick }) {
  const live = aiOn();
  const sugg = [...new Set(suggested)].map(langInfo);
  const sim = LANGS.filter((l) => l.sim);
  const more = LANGS.filter((l) => !l.sim);
  openSheet({
    title,
    html: `
      <div class="lpick">
        <label class="dsearch lpick__search">${icon('search')}<input type="search" placeholder="Search ${LANGS.length} languages" aria-label="Search languages" data-lsearch autocomplete="off"/></label>
        <div class="lpick__engine ${live ? 'is-live' : ''}">
          ${live ? `${icon('sparkle')}<span><b>Live AI is on</b><small>Every language is available. Translations are generated by Claude and marked “Live AI”.</small></span>`
            : `${icon('sparkle')}<span><b>Simulated engine</b><small>${sim.length} languages from a reviewed medical glossary. Turn on live AI for the other ${more.length}.</small></span>`}
          <button type="button" class="lpick__ai" data-ai-settings>${live ? 'Settings' : 'Set up'}</button>
        </div>
        ${sugg.length ? `<div class="lpick__sec" data-sec><h3>Suggested</h3><ul class="lgrid">${sugg.map((l) => row(l, current, live)).join('')}</ul></div>` : ''}
        <div class="lpick__sec" data-sec><h3>Offline · simulated</h3><ul class="lgrid">${sim.map((l) => row(l, current, live)).join('')}</ul></div>
        <div class="lpick__sec" data-sec><h3>Live AI ${live ? '' : '· needs your API key'}</h3><ul class="lgrid">${more.map((l) => row(l, current, live)).join('')}</ul></div>
        <p class="lpick__empty" data-lempty hidden>No language matches.</p>
      </div>`,
    mount(sheet) {
      const input = sheet.querySelector('[data-lsearch]');
      if (matchMedia('(pointer: fine)').matches) setTimeout(() => input.focus(), 50);
      input.addEventListener('input', () => {
        const q = input.value.trim().toLowerCase();
        let any = false;
        sheet.querySelectorAll('[data-sec]').forEach((sec) => {
          let n = 0;
          sec.querySelectorAll('.lrow').forEach((b) => { const on = !q || b.dataset.q.includes(q); b.parentElement.hidden = !on; if (on) n++; });
          sec.hidden = !n; if (n) any = true;
        });
        sheet.querySelector('[data-lempty]').hidden = any;
      });
      input.addEventListener('keydown', (e) => {
        if (e.key !== 'Enter') return;
        const first = [...sheet.querySelectorAll('.lrow')].find((b) => !b.parentElement.hidden && b.dataset.locked !== 'true');
        first?.click();
      });
      sheet.addEventListener('click', (e) => {
        if (e.target.closest('[data-ai-settings]')) { openAiSettings(); return; }
        const b = e.target.closest('.lrow');
        if (!b) return;
        if (b.dataset.locked === 'true') {
          toast(`${langInfo(b.dataset.lang).name} needs live AI. Set it up first.`);
          return;
        }
        closeSheet();
        onPick(b.dataset.lang);
      });
    },
  });
}

/** Live AI settings: the user pastes their own key; it stays in this browser. */
export function openAiSettings(onChange) {
  const s = aiSettings();
  openSheet({
    title: 'Live AI translation',
    html: `
      <div class="aiset">
        <p class="aiset__lead">By default MediPassport uses a <b>simulated</b> engine: a reviewed medical glossary that works offline in 12 languages. Live AI sends your records to Claude to translate any language, read new uploads and write summaries.</p>
        <ul class="aiset__list">
          <li>${icon('lock')} Your key is stored only in this browser and sent only to Anthropic.</li>
          <li>${icon('alert')} For demos and testing. Use a key with a spending limit. A real product would keep the key on a server.</li>
          <li>${icon('eye')} Results are labeled “Live AI”. Medical translations still need professional verification.</li>
        </ul>
        <label class="toggle aiset__toggle">
          <span class="toggle__txt"><b>Use live AI</b><small>Model: Claude Opus 5.5</small></span>
          <input type="checkbox" role="switch" data-ai-on ${s.enabled ? 'checked' : ''}/>
          <span class="toggle__ui" aria-hidden="true"></span>
        </label>
        <label class="aiset__key"><span>Anthropic API key</span>
          <input type="password" autocomplete="off" spellcheck="false" placeholder="sk-ant-…" value="${esc(s.key)}" data-ai-key/></label>
        <div class="aiset__actions">
          <button type="button" class="wbtn wbtn--line" data-ai-clear>${icon('refresh')} Clear saved translations</button>
          <button type="button" class="wbtn" data-ai-save>${icon('check')} Save</button>
        </div>
      </div>`,
    mount(sheet) {
      sheet.querySelector('[data-ai-save]').addEventListener('click', () => {
        const enabled = sheet.querySelector('[data-ai-on]').checked;
        const key = sheet.querySelector('[data-ai-key]').value.trim();
        if (enabled && !key) { toast('Add an API key to turn on live AI.'); return; }
        saveAiSettings({ enabled, key });
        closeSheet();
        toast(enabled ? 'Live AI is on.' : 'Using the simulated engine.');
        onChange?.();
        window.dispatchEvent(new HashChangeEvent('hashchange'));
      });
      sheet.querySelector('[data-ai-clear]').addEventListener('click', () => { clearAiCache(); toast('Saved AI translations cleared.'); });
    },
  });
}
