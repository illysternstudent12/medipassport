"""Build sw.js: precache list + a cache version derived from the files' contents.
Run from the project root after changing any app file:  python tools/make_sw.py"""
import hashlib, json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILES = ["./", "index.html", "manifest.webmanifest"]
for pattern in ("js/**/*.js", "css/*.css", "assets/*.svg", "assets/icons/*.png", "assets/demo-data/*.json", "assets/demo-docs/*.pdf"):
    FILES += sorted(p.relative_to(ROOT).as_posix() for p in ROOT.glob(pattern))

h = hashlib.sha256()
for f in FILES[1:]:
    h.update((ROOT / f).read_bytes())
version = h.hexdigest()[:10]

SW = r"""// Generated by tools/make_sw.py. Do not edit by hand.
// Offline support: the app shell and sample data are precached. Same-origin
// requests are network-first (fresh when online, cached when offline).
// Versioned libraries from CDNs are cache-first. Live services (Overpass,
// Nominatim, map tiles, Supabase) always go to the network.
const VERSION = '%s';
const CACHE = `mp-${VERSION}`;
const LIBS = 'mp-libs-v1';
const PRECACHE = %s;
const CDN = /^https:\/\/(unpkg\.com|cdnjs\.cloudflare\.com|cdn\.jsdelivr\.net|fonts\.googleapis\.com|fonts\.gstatic\.com)\//;

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('mp-') && k !== CACHE && k !== LIBS).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});

const timeout = (ms) => new Promise((_, rej) => setTimeout(() => rej(new Error('timeout')), ms));
async function networkFirst(req) {
  const cache = await caches.open(CACHE);
  try {
    const res = await Promise.race([fetch(req), timeout(4000)]);
    if (res.ok) cache.put(req, res.clone());
    return res;
  } catch {
    return (await cache.match(req, { ignoreSearch: true })) || (req.mode === 'navigate' ? cache.match('index.html') : Response.error());
  }
}
async function cacheFirst(req) {
  const cache = await caches.open(LIBS);
  const hit = await cache.match(req);
  if (hit) return hit;
  const res = await fetch(req);
  if (res.ok || res.type === 'opaque') cache.put(req, res.clone());
  return res;
}
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin === self.location.origin) { e.respondWith(networkFirst(req)); return; }
  if (CDN.test(req.url)) e.respondWith(cacheFirst(req));
  // everything else (live APIs, tiles): straight to the network
});
""" % (version, json.dumps(FILES, indent=0))
(ROOT / "sw.js").write_text(SW, encoding="utf-8")
print(f"sw.js · {len(FILES)} files · version {version}")
